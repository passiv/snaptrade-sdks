async function wrapAxiosRequest<R>(makeRequest: () => Promise<R>): Promise<R> {
    const maxAttempts = 3;
    let attempt = 0;
    let delay = 5000;
    while (attempt < maxAttempts) {
        try {
            return await makeRequest();
        } catch (e) {
            if (axios.isAxiosError(e)) {
                if (e.response?.status == 429) {
                    attempt++;
                    console.log(`429 error encountered, retrying in ${delay / 1000} seconds...`);
                    await new Promise(resolve => setTimeout(resolve, delay));
                    delay *= 2;
                    continue;
                }
                let responseBody: unknown;
                try {
                    const responseData = e.response?.data;
                    responseBody = responseData;
                    if (typeof ReadableStream !== "undefined" && responseData instanceof ReadableStream) {
                        responseBody = await readableStreamToString(responseData);
                    }
                    responseBody = parseIfJson(responseBody);
                } catch {
                    // Response inspection is best effort and must not expose the raw Axios error.
                    responseBody = undefined;
                }
                throw new SnaptradeError(e, responseBody, e.response?.headers)
            }
            throw e
        }
    }
    throw new Error(`Request failed after ${maxAttempts} retries due to 429 (rate limit) errors.`);
}

